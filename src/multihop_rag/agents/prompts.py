"""所有 prompt 模板集中在这里。

⭐ 三个 prompt 的设计要点（面试重点）：
   1. JUDGE 故意"偏向判不够"——多搜一次比答错便宜（这是一个有意的取舍）
   2. REWRITE 硬性要求"必须使用已有证据里的实体"——把自由发挥变成确定性操作
   3. GENERATE 要求"只用证据、不要用先验知识"——否则测不出检索质量
"""

# ══════════════════════════════════════════════════════════
#  1. JUDGE：判断证据是否充分
# ══════════════════════════════════════════════════════════
JUDGE_PROMPT = """你是一个检索质量评估员。判断「已有证据」是否足以回答「用户问题」。

## 用户问题
{question}

## 已有证据
{evidences}

## 判断标准（按顺序检查）
1. **子问题覆盖**：问题是否包含多个需要分别回答的部分？每部分都有证据吗？
2. **实体桥接**：如果问题形如"A 的 B"，是否既找到了 A，也找到了 A 对应的 B？
3. **明确性**：证据是「直接回答」还是只是「相关」？只是相关不算够。
4. **矛盾检查**：证据之间有没有冲突？

## 重要原则
- **宁可判「不够」，也不要勉强回答。** 多搜一次的代价远小于答错的代价。
- 如果问题需要比较两个事物，**两个都要有证据**才算够。
- 如果证据里出现了候选答案但不确定，判「不够」。

## 输出
sufficient: 证据是否充分（true/false）
missing:    还缺什么信息（若充分则为空字符串）
reasoning:  一句话说明理由
"""


# ══════════════════════════════════════════════════════════
#  2. REWRITE：生成新的检索查询
# ══════════════════════════════════════════════════════════
REWRITE_PROMPT = """用户最初的提问：
{question}

目前已检索到的证据摘要：
{evidences}

经过判断，还缺少以下信息：
{missing}

已经使用过的查询（**绝对不要重复或近似重复**）：
{used_queries}

## 任务
生成**一个新的检索查询**，用于找到缺失的信息。

## 硬性要求
1. **必须包含从已有证据中提取的具体实体名**（人名、书名、地名、机构名、术语等）。
   原始问题里的词已经搜过且搜不到，必须换成新实体。
2. 不要重复上面列出的已用查询。
3. 查询要简短，像搜索关键词，不要写成一整句话。
4. 只输出查询本身。

## 示例
原问题：拍摄《让子弹飞》的导演，还导演过哪部以民国为背景的电影？
已有证据：让子弹飞由姜文执导，2010 年上映。
缺少：该导演的其他作品
已用查询：让子弹飞 导演
→ query: 姜文 导演 民国 电影
   used_entities: ["姜文"]
"""


# ══════════════════════════════════════════════════════════
#  3. GENERATE：根据证据生成最终答案
#
#  ⭐ 这个 prompt 是根据两轮错误分析改出来的（第三版）。
#
#     第一版问题（EM 0.550）：
#       · 94.4% 的错误来自生成层，检索只占 5.6%
#       · 主因：模型用【中文】回答【英文】问题
#         ('第二次世界大战' vs 'World War II' → 语义对但 EM=0)
#       · prompt 里"证据不足就说无法确定"导致过度放弃（24 条）
#
#     第二版（EM 0.700）：修了语言 + 减少放弃 → B1 从 24 条降到 2 条
#
#     第二版残留问题（本版修正）：
#       · 答案啰嗦：'Yes. The Conewago Canal enabled...' vs 标准 'yes'
#         → 根因是"要完整"和"要简短"两条指令打架
#       · 所以本版把它们拆开，并对是/否类问题给死规则
# ══════════════════════════════════════════════════════════
GENERATE_PROMPT = """根据以下证据回答问题。

## 问题
{question}

## 证据
{evidences}

## 要求

### 1. 语言（最重要）
**答案必须用英文。** 证据是英文维基百科，问题和标准答案都是英文。
不要用中文回答，即使我们的对话界面是中文。
例：World War II ✅  第二次世界大战 ❌
    yes ✅           是 ❌
    opera ✅         歌剧 ❌

### 2. 答案部分只能有答案本身（重要）
**不要写句子，不要解释，不要加"根据证据"、"答案是"之类的话。**

按问题类型决定答案形态：

| 问题类型 | 答案形态 | 正例 | 反例 |
|---|---|---|---|
| 是/否（Do/Did/Are/Was...） | 只输出 `yes` 或 `no` | `yes` | `Yes. The canal enabled...` ❌ |
| 数量 | 只输出数字+单位 | `1340000 sqft` | `It consists of 1,340,000 square feet...` ❌ |
| 人名/专有名词 | 完整表述，但不加解释 | `Festus Claudius "Claude" McKay` | `The author is Claude McKay` ❌ |
| 其他 | 一个词或短语，最多 8 个词 | `Western Conference` | `The team belongs to the Western Conference` ❌ |

### 3. 不要轻易放弃
**证据只要与问题相关，就基于它给出你最有把握的答案。**
只有在证据与问题完全无关时才回答 cannot determine。

### 4. 只用证据
不要使用你自己的先验知识。基于上面的证据作答。

## 输出格式
答案：<your answer in English>
依据：<引用的证据标题，逗号分隔>
"""


